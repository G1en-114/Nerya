'use strict';
// Actual local service + actual MCP receipts, no mocked routes or market fixtures.
const fs = require('node:fs'), path = require('node:path');
const { promisify } = require('node:util');
const run = promisify(require('node:child_process').execFile);
const { chromium, expect } = require('@playwright/test');
const root = path.resolve(__dirname, '../..');
const reportPath = path.join(root, 'test-results/mcp-followup-verification.json');
const receipts = JSON.parse(fs.readFileSync(reportPath, 'utf8'));
const base = 'http://127.0.0.1:18380';
const result = { session_id: receipts.session_id, proposal_id: receipts.proposal_id, chart_id: receipts.chart_id, checks: {}, pageErrors: [], localModelCalls: [], screenshots: [] };
const cli = mode => run(path.join(root, '.venv/bin/python'), [path.join(root, 'scripts/verify_mcp_followup.py'), '--workspace', receipts.workspace, '--report', reportPath, '--source', receipts.source, '--mode', mode], { cwd: root, timeout: 90000 });
(async () => {
 const browser = await chromium.launch({ headless: true });
 const page = await browser.newPage({ viewport: { width: 1440, height: 1050 }, locale: 'zh-CN', reducedMotion: 'reduce' });
 page.setDefaultTimeout(15000);
 page.on('pageerror', error => result.pageErrors.push(error.message));
 page.on('request', req => { if (req.url().includes('/agent/run_turn')) result.localModelCalls.push(req.url()); });
 const shot = async name => { const file = `test-results/mcp-followup-${name}.png`; await page.screenshot({path:path.join(root,file),animations:'disabled'}); result.screenshots.push(`agent/${file}`); };
 const closeDock = async () => { const header = page.getByTestId('task-dock-header'); if (await header.isVisible()) await header.getByRole('button').last().click(); };
 try {
  if (!receipts.proposal_id || !receipts.chart_id) throw new Error('Real proposal and chart required');
  await page.goto(`${base}/chat/${receipts.session_id}`, {waitUntil:'domcontentloaded'});
  const feed = page.getByTestId('external-timeline');
  await expect(feed).toBeVisible(); await closeDock();
  for (const tool of ['read_file','list_dir','grep','run_shell','todo_write','script_run','strategy_generate']) await expect(feed.locator(`[data-testid="external-call"][data-tool="${tool}"]`).first()).toBeVisible();
  await expect(feed.locator('[data-tool="grep"]').first()).toContainText('main.agent.md');
  await feed.locator('[data-tool="todo_write"]').first().getByRole('button').first().click();
  await expect(feed.locator('[data-tool="todo_write"]').first()).toContainText('检查真实策略与品种卡片');
  await expect(feed.locator('[data-testid="external-technical-details"][open]')).toHaveCount(0);
  result.checks.general_tools_shared_trace = true;
  const proposal = feed.locator(`[data-proposal-id="${receipts.proposal_id}"]`).first();
  await expect(proposal).toBeVisible();
  await expect(proposal.getByTestId('strategy-workflow-panel')).toHaveAttribute('aria-busy','false');
  await expect(proposal.getByTestId('strategy-workflow-panel')).toContainText('界面验收草稿');
  await proposal.scrollIntoViewIfNeeded(); await shot('strategy');
  result.checks.actual_proposal_workflow = true;
  const asset = feed.getByTestId('research-instrument-card').first();
  await expect(asset).toBeVisible(); await expect(asset).toBeEnabled();
  const response = await page.request.get(`${base}/api/proxy/charts/get?id=${encodeURIComponent(receipts.chart_id)}`);
  const chart = await response.json();
  if (!response.ok() || !chart.ok || chart.payload.chart_id !== receipts.chart_id) throw new Error('Actual chart artifact did not resolve');
  const candles = chart.payload.series.find(series => series.type === 'candlestick').data, last = candles.at(-1).close;
  await expect.poll(async () => Number((await asset.getByTestId('research-card-price').innerText()).replace(/[^\d.-]/g,''))).toBe(Number(last.toFixed(2)));
  const market = receipts.calls.flatMap(call => (call.result.content || []).filter(part => part.type === 'json').map(part => part.data?.stdout_json)).filter(value => value?.chart_blocks?.some(block => block.chart_id === receipts.chart_id)).at(-1);
  if (market?.envelope?.mode !== 'live' || market.envelope.degraded || market.envelope.fallback_used) throw new Error('Live market provenance missing or degraded');
  result.market_snapshot = {chart_id:receipts.chart_id,candles:candles.length,last_close:last,provenance:market.envelope};
  await asset.click();
  await expect(page.getByTestId('research-instrument-panel')).toBeVisible();
  await expect(page.getByTestId('research-instrument-panel').getByTestId('financial-chart')).toBeVisible();
  await shot('instrument'); await closeDock();
  result.checks.actual_price_and_instrument_click = true;
  const initial = await feed.getByTestId('external-call').count();
  const delivery = cli('deliver').then(value=>({value}),error=>({error}));
  await expect(feed.locator('[data-testid="external-call"][data-tool="run_shell"][data-status="running"]').last()).toBeVisible();
  const text = `页面追加验收 ${Date.now()}：仅查看提案和行情，不审批、不启动、不交易。`;
  const composer = page.locator('[data-chat-composer]');
  await composer.locator('textarea').fill(text);
  const pending = page.waitForResponse(res=>res.url().includes('/agent/session/message/append') && res.request().method()==='POST');
  await composer.getByRole('button',{name:/^(发送|Send)$/}).click();
  const saved = await (await pending).json();
  if (!saved.ok || !saved.message?.id) throw new Error(JSON.stringify(saved));
  const message = feed.locator(`[data-turn-role="user"][data-turn-id="${saved.message.id}"]`);
  await expect(message).toHaveCount(1); await expect(message).toContainText(text);
  const delivered = await delivery; if (delivered.error) throw delivered.error;
  const actual = JSON.parse(fs.readFileSync(reportPath,'utf8')).delivery.requests.find(row=>row.id===saved.message.id);
  if (!actual || actual.message!==text) throw new Error('Typed message not in actual MCP response');
  await expect(message.getByTestId('external-message-receipt')).toHaveAttribute('data-state','delivered',{timeout:20000});
  await cli('ack');
  await expect(message.getByTestId('external-message-receipt')).toHaveAttribute('data-state','acknowledged',{timeout:20000});
  await expect(feed.getByTestId('external-activity').filter({hasText:'已收到页面追加的消息。本次仅验证'}).last()).toBeVisible();
  result.message_id = saved.message.id;
  result.checks.during_tool_delivery_and_explicit_ack = true;
  await message.scrollIntoViewIfNeeded(); await shot('messages');
  const finalCount = await feed.getByTestId('external-call').count();
  if (finalCount!==initial+2) throw new Error(`Wrong call count ${initial} -> ${finalCount}`);
  await page.reload({waitUntil:'domcontentloaded'}); await closeDock();
  await expect(message).toHaveCount(1);
  await expect(message.getByTestId('external-message-receipt')).toHaveAttribute('data-state','acknowledged');
  await expect(proposal).toBeVisible(); await expect(asset).toBeVisible();
  await expect(page.locator(`a[href="/chat/${receipts.session_id}"]`)).toHaveCount(1);
  result.checks.reload_and_same_session = true;
  await page.setViewportSize({width:390,height:844}); await closeDock();
  await composer.locator('textarea').scrollIntoViewIfNeeded(); await expect(composer.locator('textarea')).toBeVisible();
  if (await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1)) throw new Error('Mobile overflow');
  await shot('mobile'); result.checks.mobile_composer = true;
  await page.goto(`${base}/chat`,{waitUntil:'domcontentloaded'}); await expect(page.locator('textarea')).toBeVisible(); await expect(feed).toHaveCount(0);
  if (result.pageErrors.length || result.localModelCalls.length) throw new Error(JSON.stringify(result));
  result.checks.normal_chat_and_no_local_llm = true;
  fs.writeFileSync(path.join(root,'test-results/mcp-followup-ui-verification.json'),JSON.stringify(result,null,2)+'\n');
  console.log(JSON.stringify(result,null,2));
 } catch(error) {
  console.error(JSON.stringify({url:page.url(),errors:result.pageErrors,visible:(await page.locator('body').innerText()).slice(-2600)}));
  await shot('failure').catch(()=>{}); throw error;
 } finally { await browser.close(); }
})().catch(error=>{console.error(error.stack || error.message);process.exitCode=1;});
